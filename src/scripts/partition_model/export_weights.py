#!/usr/bin/env python3
"""Export the distilled per-size student MLPs to a libaom C header.

Emits av1/encoder/partition_student_weights.h: one NN_CONFIG per block size
(8/16/32/64), with weights laid out exactly as av1_nn_predict expects
(weights[node * num_inputs + i], ReLU hidden layers, linear output). The Fase D
integration includes this header and calls av1_nn_predict + av1_nn_softmax; no
new inference code is written.
"""

import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import torch  # noqa: E402
import student as studentmod  # noqa: E402
import features as featmod  # noqa: E402

